#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/audit/multi-tenancy/lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"
# shellcheck source=scripts/audit/multi-tenancy/lib/logging.sh
source "$SCRIPT_DIR/lib/logging.sh"

POSTGRES_ADMIN_URL="${POSTGRES_ADMIN_URL:-${POSTGRES_URL:-}}"
AUDIT_RLS_VERIFIER_ROLE="${AUDIT_RLS_VERIFIER_ROLE:-sg_audit_verifier}"
AUDIT_RLS_VERIFIER_PASSWORD="${AUDIT_RLS_VERIFIER_PASSWORD:-sg_audit_verifier}"
AUDIT_RLS_VERIFIER_DATABASE="${AUDIT_RLS_VERIFIER_DATABASE:-sg}"

if [[ -z "${POSTGRES_ADMIN_URL}" ]]; then
  echo "POSTGRES_ADMIN_URL or POSTGRES_URL is required" >&2
  exit 1
fi

audit_require_cmd psql

audit_log "INFO" "Provisioning RLS verifier role ${AUDIT_RLS_VERIFIER_ROLE}"

psql "${POSTGRES_ADMIN_URL}" -v ON_ERROR_STOP=1 <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM pg_roles
     WHERE rolname = '${AUDIT_RLS_VERIFIER_ROLE}'
  ) THEN
    EXECUTE format(
      'CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION',
      '${AUDIT_RLS_VERIFIER_ROLE}',
      '${AUDIT_RLS_VERIFIER_PASSWORD}'
    );
  ELSE
    EXECUTE format(
      'ALTER ROLE %I WITH LOGIN PASSWORD %L NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION',
      '${AUDIT_RLS_VERIFIER_ROLE}',
      '${AUDIT_RLS_VERIFIER_PASSWORD}'
    );
  END IF;
END
\$\$;

GRANT CONNECT ON DATABASE ${AUDIT_RLS_VERIFIER_DATABASE} TO ${AUDIT_RLS_VERIFIER_ROLE};
GRANT pg_read_all_data TO ${AUDIT_RLS_VERIFIER_ROLE};

GRANT USAGE ON SCHEMA public TO ${AUDIT_RLS_VERIFIER_ROLE};
GRANT USAGE ON SCHEMA audit TO ${AUDIT_RLS_VERIFIER_ROLE};
GRANT USAGE ON SCHEMA orchestration TO ${AUDIT_RLS_VERIFIER_ROLE};
GRANT USAGE ON SCHEMA reporting TO ${AUDIT_RLS_VERIFIER_ROLE};
GRANT USAGE ON SCHEMA security_ops TO ${AUDIT_RLS_VERIFIER_ROLE};

ALTER DEFAULT PRIVILEGES FOR ROLE sg IN SCHEMA public GRANT SELECT ON TABLES TO ${AUDIT_RLS_VERIFIER_ROLE};
ALTER DEFAULT PRIVILEGES FOR ROLE sg IN SCHEMA audit GRANT SELECT ON TABLES TO ${AUDIT_RLS_VERIFIER_ROLE};
ALTER DEFAULT PRIVILEGES FOR ROLE sg IN SCHEMA orchestration GRANT SELECT ON TABLES TO ${AUDIT_RLS_VERIFIER_ROLE};
ALTER DEFAULT PRIVILEGES FOR ROLE sg IN SCHEMA reporting GRANT SELECT ON TABLES TO ${AUDIT_RLS_VERIFIER_ROLE};
ALTER DEFAULT PRIVILEGES FOR ROLE sg IN SCHEMA security_ops GRANT SELECT ON TABLES TO ${AUDIT_RLS_VERIFIER_ROLE};
SQL

audit_log "INFO" "Provisioned verifier role ${AUDIT_RLS_VERIFIER_ROLE}"
printf 'postgresql://%s:%s@localhost:5432/%s\n' \
  "${AUDIT_RLS_VERIFIER_ROLE}" \
  "${AUDIT_RLS_VERIFIER_PASSWORD}" \
  "${AUDIT_RLS_VERIFIER_DATABASE}"
